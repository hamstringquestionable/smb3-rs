#[cfg(test)]
mod generate;

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    /// The table's own shape, checkable without the ROM: every group has
    /// three cells and something to move, and no cell or command is in two
    /// places.
    #[test]
    fn groups_are_well_formed() {
        let mut commands = BTreeSet::new();
        for g in GROUPS {
            assert!(g.slots.len() >= 3, "{}: fewer than 3 cells", g.level);
            assert!(g.slots.iter().any(|s| s.2.is_some()), "{}: nothing moves", g.level);
            let cells: BTreeSet<_> = g.slots.iter().map(|s| (s.0, s.1)).collect();
            assert_eq!(cells.len(), g.slots.len(), "{}: a cell twice", g.level);
            for offset in g.slots.iter().filter_map(|s| s.2) {
                assert!(commands.insert(offset), "{}: command {offset:#X} twice", g.level);
            }
        }
    }

    /// The same seed deals the same arrangement, and some seed moves
    /// something.
    #[test]
    fn same_seed_same_arrangement() {
        let Ok(bytes) = std::fs::read("roms/Super Mario Bros. 3 (USA) (Rev 1).nes") else { return };
        let vanilla = Rom::from_bytes_lax(&bytes, true).unwrap();
        let run = |seed| {
            let mut rom = vanilla.clone();
            randomize(&mut rom, seed);
            rom.data
        };
        assert_eq!(run(7), run(7));
        assert_ne!(run(7), vanilla.data);
    }
}
