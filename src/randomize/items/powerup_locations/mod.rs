//! Random Power Up locations: where a power-up sits in a pattern of
//! look-alike blocks is shuffled, so it can come out of any of them.
//!
//! A group is a set of block cells in one level area: a row of ? blocks, a
//! row of bricks, the 1-2 note blocks. The power-up blocks in it (the ones the
//! ? block reroll may change: flower, leaf, star and 1-up holders), and any
//! plain block that is its own command, trade places at random; a cell
//! with no command of its own shows the plain run drawn under it. Only the
//! commands' position bytes change (`b0` row, `b1` screen and column), so this
//! works the same with or without the content reroll.
//!
//! Some groups first lengthen the plain run by one ([`Group::prep`]): vanilla
//! often draws a power-up at the end of a row as the row's last block rather
//! than on top of it, and the run must reach that cell before the power-up can
//! leave it.
//!
//! [`GROUPS`] is generated from the vanilla ROM by `generate` (test-only),
//! which renders every area with the engine's own loader and keeps only cells
//! a swap provably draws correctly. `table_is_current` regenerates it and
//! fails, printing the replacement, if the two differ.
//!
//! Draws from its own substream ([`POWERUP_LOCATIONS_SALT`]), so the option
//! moves no other part of the seed.

use rand::SeedableRng;
use rand::seq::SliceRandom;
use rand_chacha::ChaCha8Rng;

use crate::rom::Rom;

/// The option's own RNG stream.
pub(crate) const POWERUP_LOCATIONS_SALT: u64 = 0x5055_505F_4C4F_4331; // "PUP_LOC1"

/// One block cell: its row, its column across the area (`screen * 16 +
/// column`, which is exactly a command's `b1`), and the file offset of the
/// command drawn there that moves with the shuffle, if any.
pub(crate) type Slot = (u8, u8, Option<usize>);

/// One pattern of look-alike blocks.
pub(crate) struct Group {
    /// The level and area: a label for the table and the write log.
    pub(crate) level: &'static str,
    /// Bytes written before the shuffle: a plain run lengthened (and, when
    /// it starts just after the power-up, moved back one) to reach under it.
    pub(crate) prep: &'static [(usize, u8)],
    pub(crate) slots: &'static [Slot],
}

/// Shuffle every group.
pub(crate) fn randomize(rom: &mut Rom, seed: u64) {
    let mut rng = ChaCha8Rng::seed_from_u64(seed ^ POWERUP_LOCATIONS_SALT);
    for group in GROUPS {
        let mut commands: Vec<Option<usize>> = group.slots.iter().map(|s| s.2).collect();
        commands.shuffle(&mut rng);
        rom.push_tag(group.level);
        arrange(rom, group.prep, group.slots, &commands);
        rom.pop_tag();
    }
}

/// Write `prep`, then put `commands[i]` at slot `i`.
fn arrange(rom: &mut Rom, prep: &[(usize, u8)], slots: &[Slot], commands: &[Option<usize>]) {
    for &(offset, value) in prep {
        rom.write_byte(offset, value);
    }
    for (&(row, column, _), command) in slots.iter().zip(commands) {
        if let Some(offset) = *command {
            let b0 = rom.read_byte(offset);
            rom.write_byte(offset, b0 & 0xE0 | row);
            rom.write_byte(offset + 1, column);
        }
    }
}

